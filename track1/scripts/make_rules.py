#!/usr/bin/env python3
"""Write a route B rules file for another disease by swapping only the disease-knowledge layer.

Route B has two parts. The engine (rank_panel.py and every number in ranking_rules.yml: points, frequency and
quality thresholds, pairing, tie-breaks, submission) knows nothing about MVA. The knowledge layer is three keys:
genes.tier_a, genes.tier_b and known_alleles. This script copies the frozen rules and replaces those three keys,
so a new disease needs a gene list, not new code or new weights.

  make_rules.py --genelists benchmark/genelists_panelapp.tsv --panel fanconi_bloom --out rules.yml
  make_rules.py --tier-a FANCA,FANCC --tier-b FAAP100 --name my_panel --out rules.yml

Gene lists: tier A = PanelApp green (confidence 3), tier B = amber (confidence 2); red genes are not used.
"""
import argparse
import csv
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from t1common import default_rules, load_rules  # noqa: E402

KNOWLEDGE_KEYS = ("genes", "known_alleles")


def read_genelists(path):
    """PanelApp snapshot → {panel: {'tier_a': [...], 'tier_b': [...], 'biallelic': set, 'id', 'version'}}."""
    out = {}
    with open(path, encoding="utf-8") as fh:
        rows = csv.DictReader((ln for ln in fh if not ln.startswith("#")), delimiter="\t")
        for r in rows:
            p = out.setdefault(r["panel"], {"tier_a": set(), "tier_b": set(), "biallelic": set(),
                                            "id": r["panelapp_id"], "version": r["version"]})
            moi = r.get("moi", "")
            if r["confidence"] == "3":
                p["tier_a"].add(r["symbol"])
            elif r["confidence"] == "2":
                p["tier_b"].add(r["symbol"])
            if moi.startswith("BIALLELIC") or moi.startswith("BOTH monoallelic and biallelic"):
                p["biallelic"].add(r["symbol"])
    for p in out.values():
        p["tier_b"] -= p["tier_a"]
        p["tier_a"], p["tier_b"] = sorted(p["tier_a"]), sorted(p["tier_b"])
    return out


def swap(base, tier_a, tier_b, known_alleles=(), aliases=None, note=""):
    """Copy of the frozen rules with only the knowledge layer replaced."""
    r = yaml.safe_load(yaml.safe_dump(base))          # deep copy
    r["genes"] = {"tier_a": list(tier_a), "tier_b": [g for g in tier_b if g not in set(tier_a)],
                  "aliases": dict(aliases or {})}
    r["known_alleles"] = list(known_alleles)
    r["derived"] = {"from_rules_version": base.get("version"), "knowledge_layer": note,
                    "unchanged": "points, frequency, spliceai, quality, pairing, merge, submission"}
    return r


def engine_part(rules):
    """Everything except the knowledge layer and provenance (used by tests to prove nothing else changed)."""
    return {k: v for k, v in rules.items() if k not in KNOWLEDGE_KEYS + ("derived",)}


def write(rules, path):
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# Generated by scripts/make_rules.py from the frozen ranking_rules.yml. Only genes and known_alleles\n")
        fh.write("# differ from the original; every weight and threshold is copied unchanged.\n")
        yaml.safe_dump(rules, fh, sort_keys=False, allow_unicode=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--rules", default=default_rules(), help="frozen rules to copy (default: config/ranking_rules.yml)")
    ap.add_argument("--genelists", help="PanelApp snapshot TSV (benchmark/genelists_panelapp.tsv)")
    ap.add_argument("--panel", help="panel key in --genelists")
    ap.add_argument("--tier-a", help="comma-separated tier A genes (instead of --genelists)")
    ap.add_argument("--tier-b", default="", help="comma-separated tier B genes")
    ap.add_argument("--name", default="custom")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    base = load_rules(a.rules)
    if a.genelists:
        if not a.panel:
            raise SystemExit("--panel is required with --genelists")
        lists = read_genelists(a.genelists)
        if a.panel not in lists:
            raise SystemExit(f"{a.panel} is not in {a.genelists}: {sorted(lists)}")
        p = lists[a.panel]
        rules = swap(base, p["tier_a"], p["tier_b"],
                     note=f"PanelApp {a.panel} (id {p['id']}, version {p['version']}): green = tier A, amber = tier B")
    elif a.tier_a:
        ta = [g.strip() for g in a.tier_a.split(",") if g.strip()]
        tb = [g.strip() for g in a.tier_b.split(",") if g.strip()]
        rules = swap(base, ta, tb, note=f"{a.name}: gene lists given on the command line")
    else:
        raise SystemExit("give --genelists and --panel, or --tier-a")
    write(rules, a.out)
    print(f"{a.out}: tier A {len(rules['genes']['tier_a'])} genes, tier B {len(rules['genes']['tier_b'])}; "
          f"weights and thresholds from rules version {base['version']}")


if __name__ == "__main__":
    main()
